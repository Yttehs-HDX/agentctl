"""The Claude Code hook script agentctl installs.

Claude Code runs one command per hook event and passes the event as JSON on
stdin. This script is a thin transport: it forwards to `agentctl hook ...` and
prints the response object Claude Code expects on stdout.

Two verified behaviours shape it:

- `UserPromptSubmit` receives `{session_id, prompt_id, prompt, ...}`; the
  agentctl marker therefore travels in `prompt`.
- `Stop` receives `{session_id, stop_hook_active, last_assistant_message}`, and
  printing `{"decision":"block","reason":"..."}` makes Claude Code continue the
  conversation with that reason. That is the idle wake.

Recursion is guarded twice: `stop_hook_active` is honoured, and the notice is
acked before it is printed so a second Stop finds an empty inbox.
"""

from __future__ import annotations

SCRIPT = """#!/bin/sh
# agentctl hook for Claude Code. Generated by `agentctl integrations install claude`.
# Forwards the hook event on stdin to agentctl and prints the object Claude Code
# expects on stdout. The launcher path is baked in below and carries its own
# AGENTCTL_HOME, so the hook depends on neither PATH nor inherited variables.
exec "{launcher}" hook claude-hook
"""


def script(launcher: str) -> str:
    return SCRIPT.format(launcher=launcher)
